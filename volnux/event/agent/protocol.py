_JSON_TYPES = {
    str: "string",
    int: "integer",
    float: "number",
    bool: "boolean",
    dict: "object",
    list: "array",
    tuple: "array",
}


def json_type(declared: Any) -> str:
    """JSON-schema type name for a type as tool parameters declare it (a Python
    type, or already a JSON type name; anything else is a string)."""
    if isinstance(declared, str):
        name = declared.lower()
        return name if name in set(_JSON_TYPES.values()) | {"null"} else "string"
    return _JSON_TYPES.get(declared, "string")


def build_tool_schemas(tools: Optional[List[Type[Any]]]) -> List[Dict[str, Any]]:
    """Neutral function schemas (``name``, ``description``, ``parameters``) for tool
    event classes, from the ``INIT_PARAMS_SCHEMA`` each declares. Provider adapters
    convert them to their own wire format."""
    import inspect

    schemas = []
    for tool_class in tools or []:
        params = getattr(tool_class, "INIT_PARAMS_SCHEMA", {}) or {}
        schemas.append(
            {
                "name": tool_class.__name__,
                "description": (
                    inspect.getdoc(tool_class) or f"Execute {tool_class.__name__}"
                )[:500],
                "parameters": {
                    "type": "object",
                    "properties": {
                        name: {
                            "type": json_type(spec.get("type", "string")),
                            "description": spec.get("description", ""),
                        }
                        for name, spec in params.items()
                    },
                    "required": [
                        name for name, spec in params.items() if spec.get("required")
                    ],
                },
            }
        )
    return schemas


