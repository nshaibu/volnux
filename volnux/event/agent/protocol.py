TRIM_MARKER = "[CONTEXT TRIMMED"


def trim_messages(
    messages: List[Dict[str, Any]], max_messages: int, step_index: int = 0
) -> List[Dict[str, Any]]:
    """Keep the conversation within ``max_messages``.

    Always kept: the system prompt (first) and the original task (second). Of the
    rest only the newest are kept, and the cut never separates a tool result from the
    assistant message that asked for it (providers reject an orphaned result). One
    marker tells the model that history was dropped; trimming again replaces it.
    """
    if max_messages < 4 or len(messages) <= max_messages:
        return messages

    head = messages[:2]
    tail = [
        m
        for m in messages[2:]
        if not (
            m.get("role") == "user"
            and str(m.get("content", "")).startswith(TRIM_MARKER)
        )
    ]
    keep = max_messages - len(head) - 1  # one slot for the marker
    cut = max(0, len(tail) - keep)
    # never start on a tool result: step forward past results whose request is gone
    while cut < len(tail) and tail[cut].get("role") == "tool":
        cut += 1
    dropped = len(messages) - len(head) - (len(tail) - cut)
    marker = {
        "role": "user",
        "content": (
            f"{TRIM_MARKER}: {dropped} earlier messages were removed to fit the "
            f"context window. Reasoning continues from step {step_index}.]"
        ),
    }
    return head + [marker] + tail[cut:]
