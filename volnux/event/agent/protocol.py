"""The agent protocol: what an agent says, how it is understood, what it may do.

An agent answers each turn with one *directive*::

    THINK:   <rationale>
    TOOL:    <tool_name> | <json_args>
    HANDOFF: <agent_name> | <json_context>
    FINISH:  <answer>
    ERROR:   <code> | <description>
    PAUSE:   <reason>

Providers with native function calling report tool calls structurally instead; the
agent treats both the same way. Everything here is pure (no I/O), so the protocol can
be tested, and reused by providers, without a model.
"""

import json
import re
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional, Tuple, Type

from ._state import AgentAction

__all__ = [
    "Directive",
    "GOVERNANCE_PROTOCOL",
    "ProtocolViolation",
    "TRIM_MARKER",
    "build_tool_schemas",
    "json_type",
    "parse_directive",
    "trim_messages",
]


class ProtocolViolation(Exception):
    """The model's response does not follow the agent protocol."""


GOVERNANCE_PROTOCOL = """
[VOLNUX GOVERNANCE FRAMEWORK]
Agent: {agent}
Permitted tools: {tools}
Permitted handoffs: {handoffs}
Max reasoning steps: {n}

────────────────────────────
RUNTIME MESSAGE TYPES
────────────────────────────
USER:        Task input. Generated by runtime only.
OBSERVATION: Tool result. Generated by runtime only.

The agent never generates USER or OBSERVATION.
The runtime never generates THINK, TOOL, HANDOFF, FINISH, or ERROR.

────────────────────────────
PROTOCOL CONTRACT
────────────────────────────
Every response MUST begin with exactly one directive token.
No second directive may appear anywhere in the response.
The first token determines the action. The runtime enforces this.

Valid directive tokens:
  THINK:    <rationale>
  TOOL:     <tool_name> | <json_args>
  HANDOFF:  <agent_name> | <json_context>
  FINISH:   <answer>
  ERROR:    <code> | <description>

────────────────────────────
GOVERNANCE RULES
────────────────────────────
1. Only use tools listed in Permitted Tools.
2. Only HANDOFF to agents listed in Permitted Handoffs.
3. Never simulate tool execution or observations.
4. Never exceed Max Reasoning Steps.
5. THINK ends your turn. The runtime re-invokes you.
6. FINISH or ERROR ends the interaction.

────────────────────────────
PROTOCOL VIOLATIONS
────────────────────────────
Violations include:
  - More than one directive in a response.
  - Simulating observations or tool results.
  - Using an unpermitted tool or handoff target.
  - Emitting conversational language.

If uncertain how to proceed:
  ERROR: RECOVERABLE | Unable to comply with protocol.

[END GOVERNANCE FRAMEWORK]
"""

_TOKENS = {
    "THINK": AgentAction.THINK,
    "TOOL": AgentAction.TOOL_CALL,
    "HANDOFF": AgentAction.HANDOFF,
    "FINISH": AgentAction.FINISH,
    "ERROR": AgentAction.ERROR,
    "PAUSE": AgentAction.PAUSE,
}
# a directive token at the start of a line (optionally behind a ReAct "Action:")
_DIRECTIVE_LINE = re.compile(
    r"^(?:Action:\s*)?(?P<token>THINK|TOOL|HANDOFF|FINISH|ERROR|PAUSE)\s*:",
    re.IGNORECASE,
)
_NAME = re.compile(r"^(?:(?P<ns>[^:|\s]+):)?(?P<name>\w+)$")


@dataclass
class Directive:
    """One understood turn of the agent."""

    action: AgentAction
    content: str = ""
    tool_name: Optional[str] = None
    tool_args: Dict[str, Any] = field(default_factory=dict)
    tool_call_id: Optional[str] = None
    namespace: Optional[str] = None
    handoff_target: Optional[str] = None
    handoff_context: Dict[str, Any] = field(default_factory=dict)
    error_code: Optional[str] = None


def _json_object(text: str, what: str) -> Dict[str, Any]:
    text = text.strip()
    if not text:
        return {}
    # models like to fence their JSON
    fenced = re.match(r"^```(?:json)?\s*(.*?)\s*```$", text, re.DOTALL | re.IGNORECASE)
    if fenced:
        text = fenced.group(1)
    try:
        value = json.loads(text)
    except json.JSONDecodeError as exc:
        raise ProtocolViolation(f"{what} is not valid JSON: {exc}") from exc
    if not isinstance(value, dict):
        raise ProtocolViolation(
            f"{what} must be a JSON object, got {type(value).__name__}"
        )
    return value


def _split_pipe(text: str) -> Tuple[str, str]:
    head, _, tail = text.partition("|")
    return head.strip(), tail.strip()


def parse_directive(text: str, *, allow_preamble: bool = False) -> Directive:
    """Understand one agent response.

    The response must begin with a directive token. ``allow_preamble`` (ReAct)
    lets lines that are not directives, such as ``Thought: ...``, come first.

    A second directive line is a violation, except after ``FINISH:``, whose body is
    free text (an answer may quote log lines that look like directives).

    Raises:
        ProtocolViolation: no directive, a second directive, or malformed arguments.
    """
    lines = (text or "").strip().splitlines()
    found = [
        (i, m)
        for i, line in enumerate(lines)
        if (m := _DIRECTIVE_LINE.match(line.strip()))
    ]
    if not found:
        raise ProtocolViolation("No directive found in the response.")

    first_index, first = found[0]
    if first_index != 0 and not allow_preamble:
        raise ProtocolViolation(
            "The response must begin with a directive token, found other text first."
        )

    token = first.group("token").upper()
    action = _TOKENS[token]
    if len(found) > 1 and action != AgentAction.FINISH:
        raise ProtocolViolation("More than one directive in a single response.")

    # everything after the token, up to the end of the response
    stripped = [line.strip() for line in lines[first_index:]]
    body = "\n".join(
        [_DIRECTIVE_LINE.sub("", stripped[0], count=1).strip(), *stripped[1:]]
    ).strip()

    if action == AgentAction.TOOL_CALL:
        name_part, args_part = _split_pipe(body)
        m = _NAME.match(name_part)
        if not m:
            raise ProtocolViolation(f"Malformed TOOL directive: {name_part!r}")
        return Directive(
            action,
            content=body,
            tool_name=m.group("name"),
            namespace=m.group("ns"),
            tool_args=_json_object(args_part, "TOOL arguments"),
        )
    if action == AgentAction.HANDOFF:
        target, context = _split_pipe(body)
        if not target:
            raise ProtocolViolation("HANDOFF names no target agent.")
        return Directive(
            action,
            content=body,
            handoff_target=target,
            handoff_context=_json_object(context, "HANDOFF context"),
        )
    if action == AgentAction.ERROR:
        code, description = _split_pipe(body)
        return Directive(
            action,
            content=description or code,
            error_code=code if description else None,
        )
    return Directive(action, content=body)


